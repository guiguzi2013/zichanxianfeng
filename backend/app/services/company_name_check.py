# -*- coding: utf-8 -*-
"""企业名称输入校验(财产线索/债务人画像共用, 2026-09-06)

产品规则(用户拍板):
- 财产线索 / 债务人画像 仅支持企业, 输入自然人名要提示用户
- 输入企业名称不全(不符合企业名称规范标准)时提示用户输入企业工商全称
- 债务尽调基于债权材料, 债务人可为自然人, 不在此拦截范围

企业名称规范标准(记入知识库): 工商全称 = 行政区划 + 字号 + 行业/经营特点 + 组织形式,
组织形式必须以 有限公司 / 有限责任公司 / 股份有限公司 / 有限合伙 / 厂 / 中心 / 事务所 /
合作社 / 研究院 / 银行 / 学校 / 医院 / 工作室 / 店 / 社 等结尾(常见后缀词见 _ORG_WORDS)。
"""
from __future__ import annotations

import re

# 企业主体词(名称中含其一 → 更像企业而非纯人名)
_ORG_WORDS = ("公司", "集团", "有限", "股份", "控股", "合伙",
              "厂", "中心", "银行", "支行", "分行", "学校", "医院",
              "事务所", "合作社", "研究院", "工作室", "店", "社",
              "协会", "基金会", "驿站", "超市", "商场", "俱乐部", "园", "部", "所")
# 组织形式词(工商全称通常以此结尾; 不以此结尾的长名称 → 疑似简称/不全)
_LEGAL_ENDINGS = ("有限公司", "有限责任公司", "股份有限公司", "集团有限公司", "有限合伙",
                  "银行", "分行", "支行", "中心", "事务所", "合作社", "研究院",
                  "学校", "医院", "厂", "店", "社", "所", "工作室", "俱乐部", "集团", "公司")
_END_RE = re.compile(r"(?:%s)$" % "|".join(sorted(_LEGAL_ENDINGS, key=len, reverse=True)))


def looks_like_person(name: str) -> bool:
    """启发式: 明显自然人(短名且无企业主体词) → True(提示填企业全称)

    与债务人画像原逻辑一致(2026-09-04), 供 财产线索/画像 共用。
    """
    t = name.strip()
    if len(t) < 2 or len(t) > 60:
        return True
    if any(w in t for w in ("有限公司", "股份", "集团", "公司", "有限合伙", "厂",
                            "中心", "银行", "学校", "医院", "事务所", "合伙")):
        return False
    # 纯中文 2-4 字无企业词 → 大概率自然人(也可能是企业简称如"青岛多元")
    if re.fullmatch(r"[\u4e00-\u9fa5]{2,4}", t):
        return True
    return False


def looks_like_abbrev(name: str) -> bool:
    """启发式: 非自然人, 但名称不含任何企业主体词或明显不像工商全称 → True(疑似简称/不全)

    例如 "青岛多元房地产开发"(无 公司/集团 等词)、"XX置业"(5 字无主体词)。
    命中时提示用户输入企业工商全称(按企业名称规范标准)。
    """
    t = name.strip()
    if looks_like_person(t):
        return False  # 自然人分支已单独提示
    if any(w in t for w in _ORG_WORDS):
        # 含主体词但非常短且不以组织形式结尾: 如 "某某公司"? 以公司结尾合法 → False
        return False
    # 不含任何企业主体词且非短人名 → 疑似字号/简称(地名+字号 或 仅字号)
    if 2 <= len(t) <= 60:
        return True
    return False
