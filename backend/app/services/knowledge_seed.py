def _seed_category(title: str, is_case: bool = False) -> str:
    """按标题推断知识分类（与现有库分类一致；新类型可在后台手动调整）"""
    if is_case:
        return "尽调案例"
    t = title
    # 优先判断精确分类（避免 M0/覆盖 等关键词误命中）
    if "术语词典" in t:
        return "术语词典"
    if "尽调规则" in t:
        return "尽调规则"
    if "M0" in t or "工业用地" in t:
        return "土地估价"
    if "商业" in t and "评估" in t:
        return "商业估价"
    if "覆盖" in t or "计量单位" in t or "抵押权人优先受偿" in t:
        return "行业常识"
    if "禁止编造" in t:
        return "平台规范"
    return "尽调法规"


def seed_knowledge() -> None:
    """按标题去重写入种子数据（幂等；新增种子会增量补入已有库）"""
    db = SessionLocal()
    try:
        existing_docs = {d.title for d in db.query(LegalDoc).all()}
        added_docs = 0
        for s in LEGAL_SEEDS:
            if s["title"] not in existing_docs:
                data = dict(s)
                data.setdefault("category", _seed_category(s["title"]))
                db.add(LegalDoc(**data))
                added_docs += 1
        if added_docs:
            logger.info("knowledge: added %d new legal docs", added_docs)

        existing_cases = {c.title for c in db.query(KnowledgeCase).all()}
        added_cases = 0
        for s in CASE_SEEDS:
            if s["title"] not in existing_cases:
                data = dict(s)
                data.setdefault("category", _seed_category(s["title"], is_case=True))
                db.add(KnowledgeCase(**data))
                added_cases += 1
        if added_cases:
            logger.info("knowledge: added %d new cases", added_cases)
        db.commit()
    except Exception:
        logger.exception("knowledge seed failed")
        db.rollback()
    finally:
        db.close()
